// The first script of every page, loaded by index.html as a plain classic <script src> in
// <head>: it runs before the first paint, which is its whole reason to exist.
//
// It used to be an INLINE script in index.html, and that alone kept `'unsafe-inline'` in the
// site CSP's script-src — which is what turned three stored-markup bugs (W1, W2, A-4) into
// script execution rather than inert text (SECURITY_SUMMARY §9 #5, F10-9). A static file on
// the site's own origin is covered by `script-src 'self'`, needs no hash to keep in step, and
// scripts/check-csp.mjs fails the lint if an inline script comes back.
//
// Keep it tiny and dependency-free: it blocks the parser for as long as it takes to fetch.
(function () {
  var root = document.documentElement;
  // Apply the saved theme before paint to avoid a flash.
  try { root.setAttribute('data-theme', localStorage.getItem('bcw_theme') || 'light'); } catch (e) { /* storage blocked */ }
  // And the saved LANGUAGE, for the same reason and one more. i18n.jsx sets <html lang> once
  // React has mounted, so until then the document claims to be English: a French reader's
  // screen reader starts in the wrong voice, the browser offers to translate a page that is
  // already in their language, and `:lang()` rules and hyphenation apply the wrong locale.
  var lang = null;
  try { lang = localStorage.getItem('bcw_lang'); } catch (e) { /* storage blocked */ }
  if (lang === 'fr' || lang === 'en') root.setAttribute('lang', lang);
  // French visitors only: start fetching the French dictionary chunk in parallel with the
  // entry instead of after it (M18). Its hashed file name is written by the build into
  // <meta name="bcw-fr-chunk"> (vite.config.js, bcwebLangPreload), ahead of this script.
  // This used to be a second inline script generated by the build.
  if (lang === 'fr') {
    var meta = document.querySelector('meta[name="bcw-fr-chunk"]');
    var href = meta && meta.getAttribute('content');
    if (href && /^\/[\w./-]+\.js$/.test(href)) {
      var l = document.createElement('link');
      l.rel = 'modulepreload';
      l.crossOrigin = '';
      l.href = href;
      document.head.appendChild(l);
    }
  }
})();
